        if (!logoutModalEl || !window.bootstrap) return;
        pendingBackGuardRearm = Boolean(fromHistoryBack);
        var modalInst = bootstrap.Modal.getOrCreateInstance(logoutModalEl);
        modalInst.show();
    }

    if (logoutModalEl) {
        logoutModalEl.addEventListener('hidden.bs.modal', function() {
            if (pendingBackGuardRearm && !submittingConfirmedLogout && window.history && window.history.pushState) {
                window.history.pushState({ sasAuthGuard: true }, '', window.location.href);
            }
            pendingBackGuardRearm = false;
        });
    }

    if (confirmLogoutForm) {
        confirmLogoutForm.addEventListener('submit', function() {
            submittingConfirmedLogout = true;
            pendingBackGuardRearm = false;
        });
    }

    document.addEventListener('click', function(e) {
        var logoutLink = e.target.closest('a[data-confirm-logout="true"], a.js-confirm-logout, a[href="logout.php"]');
        if (!logoutLink || !logoutModalEl || !window.bootstrap) return;
        e.preventDefault();

        var drawerEl = document.getElementById('quickNavDrawer');
        var drawerInst = drawerEl ? bootstrap.Offcanvas.getInstance(drawerEl) : null;
        if (drawerEl && drawerInst && drawerEl.classList.contains('show')) {
            drawerEl.addEventListener('hidden.bs.offcanvas', function() {
                openLogoutConfirmModal(false);
            }, { once: true });
            drawerInst.hide();
        } else {
            openLogoutConfirmModal(false);
        }
    });

    if (isUserLoggedIn && logoutModalEl && window.history && window.history.pushState) {
        var refUrl = document.referrer || '';
        var cameFromAuthPage = /\/(login|admin-login|register|forgot_password)\.php/i.test(refUrl);
        var isProtectedPage = /\/(my_courses|manage_courses|checkout)\.php/i.test(window.location.pathname);
        var hasGuardState = Boolean(window.history.state && window.history.state.sasAuthGuard);

        if (cameFromAuthPage || isProtectedPage || hasGuardState) {
            if (!hasGuardState) {
                window.history.replaceState({ sasAuthBase: true }, '', window.location.href);
                window.history.pushState({ sasAuthGuard: true }, '', window.location.href);

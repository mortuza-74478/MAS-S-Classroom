// Theme Management (Light / Dark Mode)
function updateThemeUI(theme) {
    var lightIcon = document.querySelector('.theme-icon-light');
    var darkIcon = document.querySelector('.theme-icon-dark');
    var toggleBtn = document.getElementById('themeToggleBtn');

    if (theme === 'dark') {
        if (lightIcon) lightIcon.classList.remove('d-none');
        if (darkIcon) darkIcon.classList.add('d-none');
        if (toggleBtn) {
            toggleBtn.setAttribute('title', 'Switch to Light Mode');
        }
    } else {
        if (lightIcon) lightIcon.classList.add('d-none');
        if (darkIcon) darkIcon.classList.remove('d-none');
        if (toggleBtn) {
            toggleBtn.setAttribute('title', 'Switch to Dark Mode');
        }
    }
}

function initTheme() {
    var savedTheme = localStorage.getItem('sas_theme') || 'light';
    document.documentElement.setAttribute('data-bs-theme', savedTheme);
    updateThemeUI(savedTheme);

    var toggleBtn = document.getElementById('themeToggleBtn');
    if (toggleBtn) {
        toggleBtn.addEventListener('click', function() {
            var currentTheme = document.documentElement.getAttribute('data-bs-theme') || 'light';
            var newTheme = (currentTheme === 'dark') ? 'light' : 'dark';
            document.documentElement.setAttribute('data-bs-theme', newTheme);
            localStorage.setItem('sas_theme', newTheme);
            updateThemeUI(newTheme);
            // Re-sync payment selections with theme colors
            document.querySelectorAll('form').forEach(syncPaymentSelection);
        });
    }
}

// Payment Selection Styling Sync (uses CSS spatial classes cleanly across Light & Dark modes)
function syncPaymentSelection(form) {
    if (!form) return;
    form.querySelectorAll('.payment-method-card').forEach(function(card) {
        var radio = card.querySelector('input[type="radio"]');
        if (radio && radio.checked) {
            card.classList.add('selected');
        } else {
            card.classList.remove('selected');
        }
    });
}

// Notice & Offer Seen/Unseen Badge Tracking with localStorage
function initNoticeOfferBadges() {
    var dataEl = document.getElementById('sas-notices-data');
    if (!dataEl) return;
    var meta = {};
    try {
        meta = JSON.parse(dataEl.textContent || '{}');
    } catch (e) {
        meta = {};
    }

    var currentNoticeIds = meta.noticeIds || [];
    var currentOfferIds = meta.offerIds || [];

    function getSeenIds(key) {
        try {
            var raw = localStorage.getItem(key);
            return raw ? JSON.parse(raw) : [];
        } catch (e) {
            return [];
        }
    }

    function saveSeenIds(key, ids) {
        try {
            localStorage.setItem(key, JSON.stringify(ids));
        } catch (e) {}
    }

    function syncBadges() {
        var seenNotices = getSeenIds('sas_seen_notices');
        var seenOffers = getSeenIds('sas_seen_offers');

        var unseenNotices = currentNoticeIds.filter(function(id) {
            return seenNotices.indexOf(id) === -1;
        });

        var unseenOffers = currentOfferIds.filter(function(id) {
            return seenOffers.indexOf(id) === -1;
        });

        // Update notice badges across desktop navbar & mobile drawer
        document.querySelectorAll('.sas-notices-badge').forEach(function(badge) {
            if (unseenNotices.length > 0) {
                badge.textContent = unseenNotices.length;
                badge.classList.remove('d-none');
            } else {
                badge.classList.add('d-none');
            }
        });

        // Update offer badges across desktop navbar & mobile drawer
        document.querySelectorAll('.sas-offers-badge').forEach(function(badge) {
            if (unseenOffers.length > 0) {
                badge.textContent = unseenOffers.length;
                badge.classList.remove('d-none');
            } else {
                badge.classList.add('d-none');
            }
        });

        // Update 3-dot quick menu alert dot when any offer or notice is unseen
        document.querySelectorAll('.sas-drawer-alert-dot').forEach(function(dot) {
            if (unseenOffers.length > 0 || unseenNotices.length > 0) {
                dot.classList.remove('d-none');
            } else {
                dot.classList.add('d-none');
            }
        });
    }

    // Run badge synchronization on page load
    syncBadges();

    // Mark all current notices as seen when the Notices modal opens
    var noticesModal = document.getElementById('publicNoticesModal');
    if (noticesModal) {
        noticesModal.addEventListener('show.bs.modal', function() {
            var seen = getSeenIds('sas_seen_notices');
            var merged = Array.from(new Set(seen.concat(currentNoticeIds)));
            saveSeenIds('sas_seen_notices', merged);
            syncBadges();
        });
    }

    // Mark all current offers as seen when the Offers modal opens
    var offersModal = document.getElementById('publicOffersModal');
    if (offersModal) {
        offersModal.addEventListener('show.bs.modal', function() {
            var seen = getSeenIds('sas_seen_offers');
            var merged = Array.from(new Set(seen.concat(currentOfferIds)));
            saveSeenIds('sas_seen_offers', merged);
            syncBadges();
        });
    }
}


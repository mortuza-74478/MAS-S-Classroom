        } else {
            bootstrap.Modal.getOrCreateInstance(targetModal).show();
        }
    });

    // Smooth, reliable navigation for modal enroll & catalog buttons without blocking
    document.addEventListener('click', function(e) {
        var btn = e.target.closest('.offer-enroll-btn');
        if (!btn) return;

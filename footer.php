                    setTimeout(function() {
                        targetElement.scrollIntoView({ behavior: 'smooth' });
                    }, 100);
                }
            }
        }
    });

    // Ensure every Bootstrap modal mounts as a direct child of <body> so backdrop-filter/overflow never traps it
    document.addEventListener('show.bs.modal', function(e) {
        if (e.target && e.target.classList && e.target.classList.contains('modal') && e.target.parentElement !== document.body) {
            document.body.appendChild(e.target);
        }
    });

    // Logout confirmation modal & Browser Back guard for authenticated sessions
    var isUserLoggedIn = <?= (function_exists('isLoggedIn') && isLoggedIn()) ? 'true' : 'false' ?>;
    var logoutModalEl = document.getElementById('logoutConfirmModal');
    var confirmLogoutForm = document.getElementById('confirmLogoutForm');

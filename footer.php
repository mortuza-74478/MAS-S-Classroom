    // Client-Side Image Preview, Pan/Zoom Crop & Guide Lines Engine
    (function initImageCropper() {
        var cropModalEl = document.getElementById('imageCropModal');
        if (!cropModalEl || !window.bootstrap) return;

        var stage = document.getElementById('cropStage');
        var stageImg = document.getElementById('cropStageImg');
        var circleMask = document.getElementById('cropCircleMask');
        var guidesOverlay = document.getElementById('cropGuidesOverlay');
        var guidesToggleBtn = document.getElementById('cropGuidesToggleBtn');
        var zoomRange = document.getElementById('cropZoomRange');
        var zoomReadout = document.getElementById('cropZoomReadout');
        var resetBtn = document.getElementById('cropResetBtn');
        var cancelBtn = document.getElementById('cropCancelBtn');
        var closeBtn = document.getElementById('cropCloseBtn');
        var applyBtn = document.getElementById('cropApplyBtn');
        var titleEl = document.getElementById('imageCropModalLabel');
        var outputInfoEl = document.getElementById('cropOutputInfo');

        var state = {
            input: null,
            loadedImg: null,
            objectUrl: null,
            fileName: 'cropped_image.png',
            targetW: 600,
            targetH: 600,
            shape: 'circle',
            baseScale: 1,
            zoom: 1,
            offsetX: 0,
            offsetY: 0,
            dragging: false,
            startX: 0,
            startY: 0,
            startOffsetX: 0,
            startOffsetY: 0,
            guidesVisible: true,
            stackedParentOpen: false
        };

        function computeBaseScale() {
            if (!state.loadedImg || !stage) return 1;
            var stageW = stage.clientWidth || 340;
            var stageH = stage.clientHeight || 340;
            var natW = state.loadedImg.naturalWidth || 1;
            var natH = state.loadedImg.naturalHeight || 1;
            return Math.max(stageW / natW, stageH / natH);
        }

        function clampOffsets() {
            if (!state.loadedImg || !stage) return;
            var stageW = stage.clientWidth || 340;
            var stageH = stage.clientHeight || 340;
            var scale = state.baseScale * state.zoom;
            var drawnW = state.loadedImg.naturalWidth * scale;
            var drawnH = state.loadedImg.naturalHeight * scale;
            var maxPanX = Math.max(0, (drawnW - stageW) / 2);
            var maxPanY = Math.max(0, (drawnH - stageH) / 2);
            state.offsetX = Math.max(-maxPanX, Math.min(maxPanX, state.offsetX));
            state.offsetY = Math.max(-maxPanY, Math.min(maxPanY, state.offsetY));
        }

        function renderTransform() {
            if (!state.loadedImg) return;
            state.baseScale = computeBaseScale();
            clampOffsets();
            var scale = state.baseScale * state.zoom;
            var natW = state.loadedImg.naturalWidth;
            var natH = state.loadedImg.naturalHeight;
            stageImg.style.width = natW + 'px';
            stageImg.style.height = natH + 'px';
            stageImg.style.transform = 'translate(-50%, -50%) translate(' + state.offsetX + 'px, ' + state.offsetY + 'px) scale(' + scale + ')';
            if (zoomReadout) zoomReadout.textContent = state.zoom.toFixed(2) + 'x';
        }

        function resetView() {
            state.zoom = 1;
            state.offsetX = 0;
            state.offsetY = 0;
            if (zoomRange) zoomRange.value = '1';
            renderTransform();
        }

        function cleanupObjectUrl() {
            if (state.objectUrl) {
                URL.revokeObjectURL(state.objectUrl);
                state.objectUrl = null;
            }
        }

        function getBase64TargetInput(inputEl) {
            if (!inputEl) return null;
            var sel = inputEl.getAttribute('data-base64-target');
            if (sel) {
                var explicit = document.querySelector(sel);
                if (explicit) return explicit;
            }
            var form = inputEl.closest('form');
            if (!form) return null;
            var fallbackName = (inputEl.getAttribute('name') || 'image') + '_cropped';
            var existing = form.querySelector('input[type="hidden"][name="' + fallbackName + '"]');
            if (existing) return existing;
            var hidden = document.createElement('input');
            hidden.type = 'hidden';
            hidden.name = fallbackName;
            hidden.value = '';
            form.appendChild(hidden);
            return hidden;
        }

        function detectCropConfig(inputEl) {
            var explicitAspect = (inputEl.getAttribute('data-crop-aspect') || '').trim();
            var explicitW = parseInt(inputEl.getAttribute('data-crop-width') || '0', 10);
            var explicitH = parseInt(inputEl.getAttribute('data-crop-height') || '0', 10);
            var explicitShape = (inputEl.getAttribute('data-crop-shape') || '').trim();
            var explicitTitle = (inputEl.getAttribute('data-crop-title') || '').trim();

            var hintText = [
                inputEl.name || '',
                inputEl.id || '',
                explicitAspect,
                inputEl.closest('.modal') ? (inputEl.closest('.modal').id || '') : ''
            ].join(' ').toLowerCase();

            var isLandscapeCourse = (explicitAspect === '16:9')
                || (explicitW > explicitH && explicitW > 0 && explicitH > 0)
                || /thumbnail|banner|cover|course_image/.test(hintText);

            var targetW = explicitW > 0 ? explicitW : (isLandscapeCourse ? 1280 : 600);
            var targetH = explicitH > 0 ? explicitH : (isLandscapeCourse ? 720 : 600);
            var shape = explicitShape || (isLandscapeCourse ? 'rect' : 'circle');

            var defaultTitle = isLandscapeCourse
                ? 'Adjust Course Thumbnail (1280x720)'
                : (/instructor/.test(hintText)
                    ? 'Adjust Instructor Photo (600x600)'
                    : (/admin/.test(hintText)
                        ? 'Adjust Admin / Role Photo (600x600)'
                        : 'Adjust Profile Photo (600x600)'));

            return {
                width: targetW,
                height: targetH,
                shape: shape,
                title: explicitTitle || defaultTitle
            };
        }

        function cancelCrop() {
            if (state.input) {
                state.input.value = '';
                var hiddenInput = getBase64TargetInput(state.input);
                if (hiddenInput) hiddenInput.value = '';
            }
            cleanupObjectUrl();
            bootstrap.Modal.getOrCreateInstance(cropModalEl).hide();
        }

        cropModalEl.addEventListener('shown.bs.modal', function() {
            var backdrops = document.querySelectorAll('.modal-backdrop');
            if (backdrops.length > 1) {
                backdrops[backdrops.length - 1].classList.add('crop-backdrop-top');
            }
            renderTransform();
        });

        cropModalEl.addEventListener('hidden.bs.modal', function() {
            cleanupObjectUrl();
            if (state.stackedParentOpen && document.querySelector('.modal.show')) {
                document.body.classList.add('modal-open');
                document.body.style.overflow = 'hidden';
            }
            state.stackedParentOpen = false;
        });

        stage.addEventListener('pointerdown', function(e) {
            if (!state.loadedImg) return;
            state.dragging = true;
            state.startX = e.clientX;
            state.startY = e.clientY;
            state.startOffsetX = state.offsetX;
            state.startOffsetY = state.offsetY;
            stage.classList.add('is-dragging');
            stage.setPointerCapture(e.pointerId);
        });

        stage.addEventListener('pointermove', function(e) {
            if (!state.dragging) return;
            state.offsetX = state.startOffsetX + (e.clientX - state.startX);
            state.offsetY = state.startOffsetY + (e.clientY - state.startY);
            renderTransform();
        });

        function stopDragging() {
            state.dragging = false;
            stage.classList.remove('is-dragging');
        }
        stage.addEventListener('pointerup', stopDragging);
        stage.addEventListener('pointercancel', stopDragging);

        if (zoomRange) {
            zoomRange.addEventListener('input', function() {
                state.zoom = parseFloat(zoomRange.value || '1');
                renderTransform();
            });
        }

        if (guidesToggleBtn) {
            guidesToggleBtn.addEventListener('click', function() {
                state.guidesVisible = !state.guidesVisible;
                guidesOverlay.classList.toggle('is-hidden', !state.guidesVisible);
                guidesToggleBtn.classList.toggle('active', state.guidesVisible);
                guidesToggleBtn.setAttribute('aria-pressed', state.guidesVisible ? 'true' : 'false');
            });
        }

        if (resetBtn) resetBtn.addEventListener('click', resetView);
        if (cancelBtn) cancelBtn.addEventListener('click', cancelCrop);
        if (closeBtn) closeBtn.addEventListener('click', cancelCrop);

        if (applyBtn) {
            applyBtn.addEventListener('click', function() {
                if (!state.loadedImg || !state.input) return;
                var stageW = stage.clientWidth || state.targetW;
                var scale = state.baseScale * state.zoom;
                var drawnW = state.loadedImg.naturalWidth * scale;
                var drawnH = state.loadedImg.naturalHeight * scale;
                var scaleToOut = state.targetW / stageW;

                var canvas = document.createElement('canvas');
                canvas.width = state.targetW;
                canvas.height = state.targetH;
                var ctx = canvas.getContext('2d');
                ctx.imageSmoothingEnabled = true;
                ctx.imageSmoothingQuality = 'high';

                var outW = drawnW * scaleToOut;
                var outH = drawnH * scaleToOut;
                var outX = (state.targetW - outW) / 2 + (state.offsetX * scaleToOut);
                var outY = (state.targetH - outH) / 2 + (state.offsetY * scaleToOut);

                ctx.drawImage(state.loadedImg, outX, outY, outW, outH);

                var dataUrl = canvas.toDataURL('image/png');
                var hiddenInput = getBase64TargetInput(state.input);
                if (hiddenInput) {
                    hiddenInput.value = dataUrl;
                }

                var previewSelector = state.input.getAttribute('data-preview-target');
                var previewTarget = previewSelector ? document.querySelector(previewSelector) : null;
                if (!previewTarget) {
                    var hostWrap = state.input.closest('.spatial-subpanel, .d-flex, .mb-2, .mb-3');
                    if (hostWrap) {
                        previewTarget = hostWrap.querySelector('img');
                    }
                }
                if (previewTarget) {
                    if (previewTarget.tagName === 'IMG') {
                        previewTarget.src = dataUrl;
                        previewTarget.classList.remove('d-none');
                        var parentWrap = previewTarget.parentElement;
                        if (parentWrap) {
                            var placeholder = parentWrap.querySelector('.crop-avatar-placeholder');
                            if (placeholder) placeholder.classList.add('d-none');
                        }
                    } else {
                        var imgTag = previewTarget.querySelector('img');
                        if (imgTag) {
                            imgTag.src = dataUrl;
                            imgTag.classList.remove('d-none');
                        } else {
                            previewTarget.innerHTML = '<img src="' + dataUrl + '" alt="Selected Preview">';
                        }
                    }
                }

                var cleanBase = state.fileName.replace(/\.[^/.]+$/, '').replace(/[^a-zA-Z0-9_-]/g, '_');
                var outName = (cleanBase || 'image') + '_' + state.targetW + 'x' + state.targetH + '.png';

                canvas.toBlob(function(blob) {
                    if (blob && typeof DataTransfer !== 'undefined') {
                        try {
                            var dt = new DataTransfer();
                            dt.items.add(new File([blob], outName, { type: 'image/png', lastModified: Date.now() }));
                            state.input.dataset.cropApplied = '1';
                            state.input.files = dt.files;
                            if (hiddenInput && state.input.files && state.input.files.length > 0) {
                                hiddenInput.value = '';
                            }
                        } catch (err) {}
                    }
                    bootstrap.Modal.getOrCreateInstance(cropModalEl).hide();
                }, 'image/png');
            });
        }

        document.addEventListener('change', function(e) {
            var input = e.target;
            if (!input || input.tagName !== 'INPUT' || input.type !== 'file') return;
            var accept = (input.getAttribute('accept') || '').toLowerCase();
            if (accept.indexOf('image') === -1 && !input.hasAttribute('data-crop-aspect')) return;
            if (input.dataset.cropApplied === '1') {
                delete input.dataset.cropApplied;
                return;
            }
            var file = input.files && input.files[0];
            if (!file || !file.type || file.type.indexOf('image/') !== 0) return;

            var cfg = detectCropConfig(input);
            state.input = input;
            state.fileName = file.name || 'image.png';
            state.targetW = cfg.width;
            state.targetH = cfg.height;
            state.shape = cfg.shape;
            state.stackedParentOpen = Boolean(document.querySelector('.modal.show'));

            var isSquare = (state.targetW === state.targetH);
            stage.classList.toggle('is-square', isSquare);
            stage.style.aspectRatio = state.targetW + ' / ' + state.targetH;
            if (circleMask) {
                circleMask.classList.toggle('d-none', state.shape !== 'circle');
            }
            if (titleEl) {
                titleEl.textContent = cfg.title;
            }
            if (outputInfoEl) {
                outputInfoEl.textContent = 'Output: ' + state.targetW + 'x' + state.targetH + ' PNG';
            }

            state.guidesVisible = true;
            guidesOverlay.classList.remove('is-hidden');
            if (guidesToggleBtn) {
                guidesToggleBtn.classList.add('active');
                guidesToggleBtn.setAttribute('aria-pressed', 'true');
            }

            cleanupObjectUrl();
            state.objectUrl = URL.createObjectURL(file);
            var img = new Image();
            img.onload = function() {
                state.loadedImg = img;
                stageImg.src = state.objectUrl;
                resetView();
                bootstrap.Modal.getOrCreateInstance(cropModalEl).show();
            };
            img.src = state.objectUrl;
        });
    })();
});

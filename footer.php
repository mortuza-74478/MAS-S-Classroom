        if (!switchTrigger || !window.bootstrap) return;
        var targetSelector = switchTrigger.getAttribute('data-switch-modal');
        var targetModal = targetSelector ? document.querySelector(targetSelector) : null;
        if (!targetModal) return;

        var currentModal = switchTrigger.closest('.modal');
